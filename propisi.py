def available() -> bool:
    return config.PROPISI_PDF.exists()


def render(pdf_page: int):
    config.PROPISI_CACHE.mkdir(parents=True, exist_ok=True)
    out = config.PROPISI_CACHE / f"p{pdf_page}"
    png = out.with_suffix(".png")
    if not png.exists():
        subprocess.run(["pdftoppm", "-f", str(pdf_page), "-l", str(pdf_page), "-r", "90", "-png",
                        "-singlefile", str(config.PROPISI_PDF), str(out)], check=True)
    return png
